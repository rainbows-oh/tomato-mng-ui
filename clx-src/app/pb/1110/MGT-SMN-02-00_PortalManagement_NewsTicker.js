/*
 * 그리드 셀의 인풋박스(ipbTxt)에서 input 이벤트 발생 시 호출.
 * 입력 중인 텍스트(displayingText)를 같은 행의 title 컬럼에 즉시 반영한다.
 * 같은 컬럼에 바인딩된 optLength 가 "글자수/120" 으로 갱신된다.
 */
function onIpbTxtInput(e) {
	var vcInput = e.control;
	var vcContext = vcInput.getBindContext();

	/* 그리드 셀 컨트롤의 바인딩 컨텍스트에는 행 번호(rowIndex)만 사용하고, 데이터셋은 직접 조회 */
	app.lookup("dsList").setValue(vcContext.rowIndex, "title", vcInput.displayingText);
}


